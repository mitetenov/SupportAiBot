func Message(key string, args ...any) string {
	s, ok := messages[key]
	if !ok {
		s = key
	}
	for i, a := range args {
		s = strings.ReplaceAll(s, fmt.Sprintf("{%d}", i), fmt.Sprint(a))
	}
	return s
}
